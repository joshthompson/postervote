const rules = new Intl.PluralRules('ru');
/** Pick the word form for n: 1 голос, 2 голоса, 5 голосов. */
const plural = (n: number, one: string, few: string, many: string) =>
  ({ one, few, many })[rules.select(n) as 'one' | 'few' | 'many'] ?? many;
